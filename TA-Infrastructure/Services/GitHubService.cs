using Octokit;
using System;
using System.Collections.Generic;
using System.Text;
using TA_Application.DTOs;
using TA_Application.Interfaces.Repositories;
using TA_Application.Interfaces.Services;
using TA_Application.Services;
using TA_Domain.Entities;

namespace TA_Infrastructure.Services
{
    public class GitHubService : IGitHubService
    {
        private readonly IGitHubClientFactory _gitHubClientFactory;
        private readonly ITasksService _tasksService;
        private readonly IPullRequestRepository _prRepo;

        public GitHubService(IGitHubClientFactory gitHubClientFactory, ITasksService tasksService, IPullRequestRepository prRepo)
        {
            _gitHubClientFactory = gitHubClientFactory;
            _tasksService = tasksService;
            _prRepo = prRepo;
        }

        public async Task<PullRequestDTO> CreatePullRequestAsync(
            PullRequestCreationDTO dto,
            GitHubConfigDTO config)
        {
            // 🔐 Apply token dynamically
            var client = _gitHubClientFactory.Create(config.AccessToken);
            // 1. Get main branch
            var mainBranch = await client.Git.Reference.Get(
                config.RepoOwner,
                config.RepoName,
                $"heads/{config.DefaultBranch}"
            );

            // 2. Create branch
            string branchName = $"feat/task-{dto.TaskId}-{DateTime.Now.Ticks}";

            await client.Git.Reference.Create(
                config.RepoOwner,
                config.RepoName,
                new NewReference($"refs/heads/{branchName}", mainBranch.Object.Sha)
            );

            // 3. Get tree
            var tree = await client.Git.Tree.GetRecursive(
                config.RepoOwner,
                config.RepoName,
                config.DefaultBranch
            );

            var fileChanges = new List<NewTreeItem>();

            var treeLookup = tree.Tree
    .Where(t => t.Type == TreeType.Blob)
    .ToDictionary(t => t.Path, t => t);

            foreach (var file in dto.Files)
            {
                if (file == null) continue;

                var path = file.FileName.Replace("\\", "/").TrimStart('/');

                var existingFile = tree.Tree
                    .FirstOrDefault(t => t.Type == TreeType.Blob &&
                                         t.Path == path);

                var blob = await client.Git.Blob.Create(
                    config.RepoOwner,
                    config.RepoName,
                    new NewBlob
                    {
                        Content = file.Content,
                        Encoding = EncodingType.Utf8
                    });

                fileChanges.Add(new NewTreeItem
                {
                    Path = path,
                    Mode = "100644",
                    Type = TreeType.Blob,
                    Sha = blob.Sha
                });
            }

            if (!fileChanges.Any()) return null;

            // 4. Create tree
            var nt = new NewTree { BaseTree = tree.Sha };
            foreach (var change in fileChanges)
                nt.Tree.Add(change);

            var newTree = await client.Git.Tree.Create(
                config.RepoOwner,
                config.RepoName,
                nt
            );

            // 5. Commit
            var commit = await client.Git.Commit.Create(
                config.RepoOwner,
                config.RepoName,
                new NewCommit(
                    $"Automated update for Task {dto.TaskId}",
                    newTree.Sha,
                    new[] { mainBranch.Object.Sha }
                )
            );

            await client.Git.Reference.Update(
                config.RepoOwner,
                config.RepoName,
                $"heads/{branchName}",
                new ReferenceUpdate(commit.Sha)
            );

            // 6. PR
            var pr = await client.PullRequest.Create(
                config.RepoOwner,
                config.RepoName,
                new NewPullRequest(
                    $"Task Automation: {dto.TaskId}",
                    branchName,
                    config.DefaultBranch
                )
                {
                    Body = "Automated PR generated by TaskAutomation-APP"
                });

            return new PullRequestDTO
            {
                Id = pr.Number,
                TaskId = dto.TaskId,
                BranchName = branchName,
                PRUrl = pr.HtmlUrl,
                PRName = pr.Title,
                PRDescription = pr.Body,
                Status = pr.State.Value.ToString(),
            };
        }
        public async Task<ReviewDTO> SubmitReviewAsync(ReviewRequestDTO dto, GitHubConfigDTO config)
        {
            // 1. Get the Repo Config and the local PR record
            var client = _gitHubClientFactory.Create(config.AccessToken);
            var pr = await _prRepo.GetPullRequestById(dto.PrID); 
            // 2. Map the string action from your UI to Octokit's Enum
            // Options: Approve, RequestChanges, Comment
            var reviewEvent = dto.Decision.ToLower() switch
            {
                "approve" => PullRequestReviewEvent.Approve,
                "reject" => PullRequestReviewEvent.RequestChanges,
                _ => PullRequestReviewEvent.Comment
            };

            // 3. Send the Review to GitHub
            var reviewRequest = new PullRequestReviewCreate
            {
                Body = dto.Comment,
                Event = reviewEvent
            };

            var ghReview = await client.PullRequest.Review.Create(
                config.RepoOwner,
                config.RepoName,
                ((int)pr.ExternalId),
                reviewRequest);

            // 4. Create the Review record for your database
            var reviewEntity = new ReviewDTO
            {
                PRId = dto.PrID,
                Comment = dto.Comment,
                TaskId = dto.TaskId,
                UserId = dto.UserId,
                Decision = ghReview.State.Value.ToString(), // "APPROVED", "CHANGES_REQUESTED"
            };

            return reviewEntity;
         
        }
    }

}
