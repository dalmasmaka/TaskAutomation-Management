using Octokit;
using TA_Application.DTOs;
using TA_Application.Interfaces.Repositories;
using TA_Application.Interfaces.Services;
using TA_Domain.Entities;

namespace TA_Infrastructure.Services
{
    public class GitHubService : IGitHubService
    {
        private readonly IGitHubClientFactory _gitHubClientFactory;
        private readonly ITasksService _tasksService;
        private readonly IPullRequestRepository _prRepo;

        public GitHubService(IGitHubClientFactory gitHubClientFactory, ITasksService tasksService, IPullRequestRepository prRepo)
        {
            _gitHubClientFactory = gitHubClientFactory;
            _tasksService = tasksService;
            _prRepo = prRepo;
        }
        public async Task<TA_Domain.Entities.PullRequest> CreatePullRequestAsync(
        PullRequestCreationDTO dto,
        GitHubConfig config,
        UserGitHubConfig userConfig)
        {
            if (dto?.Files == null || !dto.Files.Any())
                throw new ArgumentException("No files provided for pull request creation.");

            var client = _gitHubClientFactory.Create(userConfig.AccessToken);

            // 1. Get main branch reference
            var mainBranchRef = await client.Git.Reference.Get(
                config.RepoOwner,
                config.RepoName,
                $"heads/{config.DefaultBranch}"
            );

            // 2. Create unique feature branch
            var branchName = $"feat/task-{dto.TaskId}-{Guid.NewGuid():N}";

            await client.Git.Reference.Create(
                config.RepoOwner,
                config.RepoName,
                new NewReference($"refs/heads/{branchName}", mainBranchRef.Object.Sha)
            );

            // 3. Get base tree from default branch SHA
            var baseTree = await client.Git.Tree.GetRecursive(
                config.RepoOwner,
                config.RepoName,
                mainBranchRef.Object.Sha
            );

            var fileChanges = new List<NewTreeItem>();

            foreach (var file in dto.Files)
            {
                if (file == null || string.IsNullOrWhiteSpace(file.FileName))
                    continue;

                var path = file.FileName.Replace("\\", "/").TrimStart('/');

                var blob = await client.Git.Blob.Create(
                    config.RepoOwner,
                    config.RepoName,
                    new NewBlob
                    {
                        Content = file.Content,
                        Encoding = EncodingType.Utf8
                    });

                fileChanges.Add(new NewTreeItem
                {
                    Path = path,
                    Mode = "100644",
                    Type = TreeType.Blob,
                    Sha = blob.Sha
                });
            }

            if (!fileChanges.Any())
                throw new InvalidOperationException("No valid file changes were generated.");

            // 4. Create new tree
            var newTreeRequest = new NewTree
            {
                BaseTree = baseTree.Sha
            };

            foreach (var change in fileChanges)
                newTreeRequest.Tree.Add(change);

            var newTree = await client.Git.Tree.Create(
                config.RepoOwner,
                config.RepoName,
                newTreeRequest
            );

            // 5. Create commit on top of main branch
            var commit = await client.Git.Commit.Create(
                config.RepoOwner,
                config.RepoName,
                new NewCommit(
                    $"Automated update for Task {dto.TaskId}",
                    newTree.Sha,
                    new[] { mainBranchRef.Object.Sha }
                )
            );

            // 6. Move branch pointer to new commit
            await client.Git.Reference.Update(
                config.RepoOwner,
                config.RepoName,
                $"heads/{branchName}",
                new ReferenceUpdate(commit.Sha)
            );

            // 7. Create pull request
            var pr = await client.PullRequest.Create(
                config.RepoOwner,
                config.RepoName,
                new NewPullRequest(
                    $"Task Automation: {dto.TaskId}",
                    branchName,
                    config.DefaultBranch
                )
                {
                    Body = "Automated PR generated by TaskAutomation-APP"
                });

            return new TA_Domain.Entities.PullRequest
            {
                Id = pr.Number,
                TaskId = dto.TaskId,
                BranchName = branchName,
                PRUrl = pr.HtmlUrl,
                PRName = pr.Title,
                PRDescription = pr.Body,
                Status = pr.State.Value.ToString() ?? "Unknown",
                CreatedById = dto.UserId
            };
        }
        public async Task<Review> SubmitReviewAsync(Review entity, GitHubConfig config, CancellationToken ct)
        {
            ArgumentNullException.ThrowIfNull(entity);
            ArgumentNullException.ThrowIfNull(config);

            var client = _gitHubClientFactory.Create(config.AccessToken);

            var pr = await _prRepo.GetPullRequestById(entity.PullRequestId, ct);
            if (pr is null)
                throw new InvalidOperationException("Pull request not found.");

            var decision = entity.Decision?.Trim().ToLowerInvariant();

            var reviewEvent = decision switch
            {
                "approve" => PullRequestReviewEvent.Approve,
                "reject" => PullRequestReviewEvent.RequestChanges,
                _ => PullRequestReviewEvent.Comment
            };

            var reviewRequest = new PullRequestReviewCreate
            {
                Body = entity.Comment,
                Event = reviewEvent
            };

            var ghReview = await client.PullRequest.Review.Create(
                config.RepoOwner,
                config.RepoName,
                (int)pr.ExternalId,
                reviewRequest);

            return new Review
            {
                PullRequestId = entity.PullRequestId,
                Comment = entity.Comment,
                Decision = ghReview.State.Value.ToString(),
                //ExternalReviewId = ghReview.Id
            };
        }
    }

}
